"""Source-backed palette-cycle coverage map for SCUMM v5 room backgrounds.

Records exactly which native indexed-background pixels use CYCL ranges.
This is a spatial provenance/export tool, NOT a runtime animation verifier.
No ScummVM code, original game resources, or artwork are bundled.
"""
from __future__ import annotations

from collections import Counter
from hashlib import sha256
import json
from pathlib import Path

from .extraction import _write_new_verified
from .inspector import XOR_KEY, _read_pair, inspect, InspectionError
from .object_images import ImageDecodeError, encode_png
from .palette_probe import (
    PaletteProbeError, decode_room_background_indexed, prepare_cycles,
)


def analyze_cycle_coverage(indexed_pixels: bytes, *, width: int, height: int,
                           records: list[dict]) -> tuple[dict, list[bytes]]:
    """Return a union mask, per-cycle counts/bounds and exact 0/255 masks.

    A pixel belonging to overlapping cycle ranges counts once in the union,
    and separately in each cycle. Region labels (water, lights, etc.) must
    come from independently reviewed imagery, not generated by this function.
    """
    if (type(width) is not int or type(height) is not int or
            width <= 0 or height <= 0 or width * height != len(indexed_pixels)):
        raise PaletteProbeError("COVERAGE_DIMENSIONS_INVALID",
                                "Indexed-background dimensions do not match buffer")
    cycles, issues = prepare_cycles(records)
    if any(x["severity"] == "error" for x in issues):
        raise PaletteProbeError("COVERAGE_CYCLE_UNSUPPORTED",
                                "Cannot map invalid palette-cycle rate")
    union = bytearray(width * height)
    masks = []
    summaries = []
    all_counts = Counter(indexed_pixels)
    for cycle in cycles:
        a, b = cycle["start_color"], cycle["end_color"]
        # Multiple cycles may affect one palette index. Union must not double-count.
        relevant = set(range(a, b + 1))
        mask = bytearray(width * height)
        min_x, min_y, max_x, max_y = width, height, -1, -1
        count = 0
        for pos, color in enumerate(indexed_pixels):
            if color not in relevant:
                continue
            y, x = divmod(pos, width)
            union[pos] = 255
            mask[pos] = 255
            count += 1
            min_x = min(min_x, x)
            min_y = min(min_y, y)
            max_x = max(max_x, x)
            max_y = max(max_y, y)
        summaries.append({
            "id": cycle["id"], "start_color": a, "end_color": b,
            "rate_raw": cycle["rate_raw"], "flags_raw": cycle["flags_raw"],
            "source_offset": cycle["source_offset"],
            "source_range_index_frequency": {
                str(i): all_counts[i] for i in range(a, b + 1)
            },
            "native_pixel_count": count,
            "native_bounds_xyxy_inclusive": (
                [min_x, min_y, max_x, max_y] if count else None
            ),
        })
        masks.append(bytes(mask))
    return {
        "native_size": [width, height],
        "total_native_pixels": width * height,
        "cycle_records": len(cycles),
        "union_pixel_count": sum(v > 0 for v in union),
        "union_fraction": sum(v > 0 for v in union) / (width * height),
        "union_mask_sha256": sha256(union).hexdigest(),
        "cycles": summaries,
        "cycle_diagnostics": issues,
    }, [bytes(union), *masks]


def export_cycle_coverage(input_path: str | Path, output_dir: str | Path, *,
                          room_id: int) -> dict:
    src, dest = Path(input_path), Path(output_dir)
    result = {
        "schema_version": "0.1", "operation": "palette_cycle_coverage",
        "input": str(src), "output_dir": str(dest), "room_id": room_id,
        "status": "failed", "summary": {}, "files": [], "diagnostics": [],
        "evidence_level": "directly_decoded_source_pixels_and_CYCL_ranges",
        "runtime_palette_changes_observed": False,
        "animation_timing_verified": False,
        "region_labels_inferred": False,
    }

    def report_issue(code: str, message: str, *, severity="error"):
        result["diagnostics"].append({
            "severity": severity, "code": code, "message": message,
            "source": str(src), "room_id": room_id,
        })

    if type(room_id) is not int or not 0 <= room_id <= 255:
        report_issue("ROOM_ID_INVALID", "Room ID must be an integer in 0..255")
        return result
    if dest.is_symlink() or (dest / "manifest.json").exists():
        report_issue("OUTPUT_COLLISION",
                     "Output path is a symlink or manifest exists; refusing overwrite")
        return result
    inventory = inspect(src)
    result["diagnostics"].extend(inventory["diagnostics"])
    if inventory["status"] != "success":
        report_issue("COVERAGE_INSPECTION_FAILED", "Original resource inspection failed")
        return result
    matches = [r for r in inventory["resources"]["rooms"] if r["id"] == room_id]
    if len(matches) != 1:
        report_issue("COVERAGE_ROOM_NOT_FOUND",
                     f"Expected exactly one room {room_id}; found {len(matches)}")
        return result
    try:
        _, stored, _, label = _read_pair(src)
        original_sha = sha256(stored).hexdigest()
        if original_sha != inventory["sources"][1]["sha256"]:
            raise PaletteProbeError("COVERAGE_SOURCE_CHANGED",
                                    "Original archive changed between inspection and decode")
        decoded = bytes(x ^ XOR_KEY for x in stored)
        room = matches[0]
        background = decode_room_background_indexed(
            decoded, room_offset=room["room_offset"],
            room_length=room["room_size"])
        summary, masks = analyze_cycle_coverage(
            background["indexed_pixels"], width=background["width"],
            height=background["height"], records=room["palette_cycles"])
        result["summary"] = summary
        result["source"] = {
            "resource_name": label, "resource_sha256": original_sha,
            "background_index_sha256": background["pixel_indices_sha256"],
            "initial_palette_sha256": background["initial_palette_sha256"],
            **background["source"],
        }
        for diag in background["diagnostics"] + summary["cycle_diagnostics"]:
            report_issue(diag["code"], diag["message"],
                         severity=diag["severity"])
        dest.mkdir(parents=True, exist_ok=True)
        width, height = background["width"], background["height"]

        # Alpha = 0 outside cycle pixels; fully opaque bright orange inside.
        # This image is a coordinate mask, NOT a recreation of source graphics.
        union = masks[0]
        overlay = b"".join(
            b"\xff\x60\x20\xff" if bit else b"\x00\x00\x00\x00"
            for bit in union
        )
        name = f"room-{room_id:03d}_all-cycle-pixels.png"
        digest = _write_new_verified(
            dest / name, encode_png(width, height, overlay, rgba=True))
        result["files"].append({
            "name": name, "kind": "transparent_rgba_coordinate_overlay",
            "sha256": digest,
        })
        for cycle, mask in zip(summary["cycles"], masks[1:]):
            name = f"room-{room_id:03d}_cycle-{cycle['id']:02d}_mask.png"
            digest = _write_new_verified(
                dest / name, encode_png(width, height, mask, rgba=False))
            result["files"].append({
                "name": name, "kind": "single_cycle_grayscale_mask",
                "cycle_id": cycle["id"], "sha256": digest,
            })
        result["status"] = "success"
    except (OSError, ValueError, InspectionError, ImageDecodeError,
            PaletteProbeError) as exc:
        report_issue(getattr(exc, "code", "COVERAGE_EXPORT_ERROR"),
                     f"{type(exc).__name__}: {exc}")
        result["status"] = "partial" if result["files"] else "failed"
    if result["files"]:
        try:
            _write_new_verified(
                dest / "manifest.json",
                (json.dumps(result, indent=2) + "\n").encode("utf-8"))
        except OSError as exc:
            report_issue("MANIFEST_WRITE_FAILED", str(exc))
            result["status"] = "partial"
    return result
